// Embeds supabase/migrations/*.sql into a TS module so preview mode can build
// its in-memory database without reading files at runtime.
import { readdir, readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'

const dir = path.join(process.cwd(), 'supabase', 'migrations')
const files = (await readdir(dir)).filter((f) => f.endsWith('.sql')).sort()
const entries = await Promise.all(files.map(async (f) => [f, await readFile(path.join(dir, f), 'utf8')]))
const out = `// AUTO-GENERATED by scripts/embed-migrations.mjs — do not edit.\nexport const MIGRATIONS: [string, string][] = ${JSON.stringify(entries, null, 2)}\n`
await writeFile(path.join(process.cwd(), 'src', 'lib', 'db', 'migrations.generated.ts'), out)
console.info(`embedded ${files.length} migrations`)
